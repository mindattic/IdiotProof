using System.Text;
using IdiotProof.Operations;

namespace IdiotProof.Cli;

/// <summary>
/// Renders docs/CLI_COMMANDS.md from the reflected operation catalog (never hand-edited), the CLI
/// twin of the MCP server's docs/MCP_TOOLS.md. Regenerate with <c>idiotproof --export-commands</c>.
/// </summary>
public static class CommandDocs
{
    public static string Render(OperationCatalog catalog)
    {
        var ops = catalog.Operations.OrderBy(o => o.Noun, StringComparer.Ordinal).ThenBy(o => o.Verb, StringComparer.Ordinal).ToList();
        var sb = new StringBuilder();
        sb.AppendLine("# idiotproof commands");
        sb.AppendLine();
        sb.AppendLine("<!-- Generated by `idiotproof --export-commands`. Do not hand-edit. -->");
        sb.AppendLine();
        sb.AppendLine($"{ops.Count} operations, each also an MCP tool (`noun_verb`). Every one runs inside the IdiotProof Hub");
        sb.AppendLine("(`idiotproof hub start`), so all data and every transaction goes through it. Global flags: `--json`, `--user <guid>`,");
        sb.AppendLine("`--confirm <code>`, `--hub <url>`, `--no-color`, `-h`. Exit codes: 0 ok, 1 failed, 2 usage, 3 blocked by a gate,");
        sb.AppendLine("4 confirmation required. Times are US Eastern.");
        sb.AppendLine();
        sb.AppendLine("| Command | Risk | What it does |");
        sb.AppendLine("|---|---|---|");
        foreach (var op in ops)
            sb.AppendLine($"| [`{op.Name}`](#{Anchor(op.Name)}) | {op.Risk} | {op.Summary.Replace("|", "\\|")} |");

        foreach (var noun in ops.GroupBy(o => o.Noun))
        {
            sb.AppendLine();
            sb.AppendLine($"## {noun.Key}");
            foreach (var op in noun)
            {
                sb.AppendLine();
                sb.AppendLine($"### {op.Name}");
                sb.AppendLine();
                sb.AppendLine("```text");
                sb.AppendLine(op.Help.TrimEnd());
                sb.AppendLine("```");
            }
        }
        return sb.ToString().ReplaceLineEndings("\n");
    }

    /// <summary>GitHub's heading anchor for <c>### noun verb</c>.</summary>
    private static string Anchor(string name) => name.ToLowerInvariant().Replace(' ', '-');
}
