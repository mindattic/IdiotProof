public sealed partial class MomentumTracker
{
    public const string ReportFileName = "momentum-claims-report.md";

    /// <summary>docs/research/momentum-claims-report.md in the repo when one is found above the working folder, else under the data folder.</summary>
    public static string DefaultReportPath()
    {
        foreach (var start in new[] { Directory.GetCurrentDirectory(), AppContext.BaseDirectory })
        {
            var dir = new DirectoryInfo(start);
            while (dir is not null)
            {
                if (File.Exists(Path.Combine(dir.FullName, "IdiotProof.slnx"))) return Path.Combine(dir.FullName, "docs", "research", ReportFileName);
                dir = dir.Parent;
            }
        }
        return Path.Combine(DefaultDir, ReportFileName);
    }

    private sealed record Row(MomentumClaim Claim, MomentumVideo? Video, MomentumClaimOutcome? Outcome, StoredScenario? Scenario);

    public async Task<MomentumRunResult> ReportAsync(DateOnly? since, string? outPath, CancellationToken ct)
    {
        await using var db = await dbFactory.CreateDbContextAsync(ct);
        var videos = await db.MomentumVideos.AsNoTracking().ToDictionaryAsync(v => v.VideoId, ct);
        var transcripts = await db.MomentumTranscripts.AsNoTracking().Select(t => new { t.VideoId, t.TradeDate, HasText = t.Text != null && t.Text != "", t.ExtractedUtc, t.ExtractError }).ToListAsync(ct);
        var cq = db.MomentumClaims.AsNoTracking();
        if (since is { } s) cq = cq.Where(c => c.TradeDate >= s);
        var claims = await cq.ToListAsync(ct);
        var ids = claims.Select(c => c.Id).ToHashSet();
        var outcomes = (await db.MomentumClaimOutcomes.AsNoTracking().ToListAsync(ct)).Where(o => ids.Contains(o.ClaimId)).ToList();
        var byClaim = outcomes.GroupBy(o => o.ClaimId).ToDictionary(g => g.Key, g => g.OrderBy(o => o.ScenarioIndex).ToList());

        var picks = claims.Where(c => c.ClaimType is PickWatchlist or PickMorning).ToList();
        var brags = claims.Where(c => c.ClaimType == Brag).ToList();
        var statements = claims.Where(c => c.ClaimType == Statement).ToList();
        var rows = new List<Row>();
        foreach (var c in picks)
        {
            var sc = Scenarios(c);
            var os = byClaim.GetValueOrDefault(c.Id) ?? [];
            int n = Math.Max(sc.Count, os.Count);
            if (n == 0) rows.Add(new Row(c, videos.GetValueOrDefault(c.VideoId), null, null));
            for (int i = 0; i < n; i++)
                rows.Add(new Row(c, videos.GetValueOrDefault(c.VideoId), os.FirstOrDefault(o => o.ScenarioIndex == i), i < sc.Count ? sc[i] : null));
        }

        var evaluated = rows.Where(r => r.Outcome is { } o && o.Verdict is not MomentumVerdicts.Unverifiable).Select(r => r.Outcome!).ToList();
        var triggered = evaluated.Where(o => o.TriggerHit).ToList();
        var entered = evaluated.Where(o => o.PlanPnlPct is not null).ToList();
        var pickOutcomes = picks.Where(c => byClaim.ContainsKey(c.Id)).Select(c => (Claim: c, Os: byClaim[c.Id])).ToList();
        var pickEvaluated = pickOutcomes.Where(p => p.Os.Any(o => o.Verdict is not MomentumVerdicts.Unverifiable)).ToList();
        var withRank = pickOutcomes.Where(p => p.Os[0].TopGapper is not null).ToList();
        var bragOutcomes = brags.Where(c => byClaim.ContainsKey(c.Id)).Select(c => (Claim: c, O: byClaim[c.Id][0])).ToList();
        var bragJudged = bragOutcomes.Where(b => b.O.Verdict is MomentumVerdicts.BragAccurate or MomentumVerdicts.BragExaggerated).ToList();
        var pending = claims.Count(c => c.ClaimType != Statement && !IsComplete(c.TradeDate));
        var lockedHoldout = claims.Count(c => c.TradeDate >= StudyLockedHoldout.From && c.TradeDate <= StudyLockedHoldout.To);

        var md = new StringBuilder();
        var nowEt = MinuteBarMath.ToEastern(NowUtc);
        var dates = claims.Select(c => c.TradeDate).DefaultIfEmpty().ToList();
        md.AppendLine("# Momentum. claim tracker (IP-T493)");
        md.AppendLine();
        md.AppendLine($"Living report, regenerated by `momentum report` (tools/MomentumTracker or `idiotproof momentum report`). Generated {nowEt:yyyy-MM-dd h:mm tt} ET" +
                      (claims.Count > 0 ? $"; trade dates {dates.Min():yyyy-MM-dd} to {dates.Max():yyyy-MM-dd}" : "") + (since is { } ss ? $"; since {ss:yyyy-MM-dd}" : "") + ".");
        md.AppendLine();
        md.AppendLine("Source: the \"Momentum.\" YouTube channel (https://www.youtube.com/@trade.momentum/shorts), daily \"TOP 3 STOCKS\" watchlist shorts and \"TOP 3 STOCKS UPDATE\" morning updates. " +
                      "Transcripts are YouTube captions; claims are extracted by an LLM (" + MomentumClaimExtractor.ExtractedBy + ") and every level is checked against Alpaca 1-minute SIP bars (04:00-20:00 ET).");
        md.AppendLine();

        // ── coverage ──
        md.AppendLine("## Coverage");
        md.AppendLine();
        md.AppendLine("| | count |");
        md.AppendLine("|---|---:|");
        md.AppendLine($"| Videos known (kept in the channel list or imported) | {videos.Count} |");
        md.AppendLine($"| Transcript files imported | {transcripts.Count} |");
        md.AppendLine($"| with caption text | {transcripts.Count(t => t.HasText)} |");
        md.AppendLine($"| without text (caption error / rate limit, retried by the collector) | {transcripts.Count(t => !t.HasText)} |");
        md.AppendLine($"| Transcripts extracted | {transcripts.Count(t => t.ExtractedUtc != null)} |");
        md.AppendLine($"| Picks (watchlist / morning update) | {picks.Count} ({picks.Count(c => c.ClaimType == PickWatchlist)} / {picks.Count(c => c.ClaimType == PickMorning)}) |");
        md.AppendLine($"| Picks with a validated ticker | {picks.Count(c => c.Symbol != null)} |");
        md.AppendLine($"| Scenarios (plans) on those picks | {rows.Count(r => r.Scenario != null)} |");
        md.AppendLine($"| Brags / market statements | {brags.Count} / {statements.Count} |");
        md.AppendLine($"| Scenario outcomes evaluated (priced trigger and bars) | {evaluated.Count} |");
        md.AppendLine($"| Unverifiable scenarios | {rows.Count(r => r.Outcome?.Verdict == MomentumVerdicts.Unverifiable)} |");
        md.AppendLine($"| Claims waiting for their session to finish | {pending} |");
        md.AppendLine();

        // ── headline ──
        md.AppendLine("## Headline (per scenario)");
        md.AppendLine();
        md.AppendLine("| metric | value |");
        md.AppendLine("|---|---:|");
        md.AppendLine($"| Scenarios evaluated | {evaluated.Count} |");
        md.AppendLine($"| Trigger rate | {Rate(triggered.Count, evaluated.Count)} |");
        md.AppendLine($"| First target hit, of triggered | {Rate(triggered.Count(o => o.FirstTargetHit), triggered.Count)} |");
        md.AppendLine($"| Any target hit, of triggered | {Rate(triggered.Count(o => o.AnyTargetHit), triggered.Count)} |");
        md.AppendLine($"| First target hit, of all evaluated | {Rate(evaluated.Count(o => o.FirstTargetHit), evaluated.Count)} |");
        md.AppendLine($"| Stopped (close under the invalidation before the first target), of triggered | {Rate(triggered.Count(o => o.Verdict == MomentumVerdicts.Stopped), triggered.Count)} |");
        md.AppendLine($"| Triggered, no target, not stopped | {Rate(triggered.Count(o => o.Verdict == MomentumVerdicts.TriggeredNoTarget), triggered.Count)} |");
        md.AppendLine($"| Plans entered (confirm reached when required) | {entered.Count} |");
        md.AppendLine($"| Hypothetical plan P&L, mean / median | {Mean(entered.Select(o => o.PlanPnlPct!.Value))} / {Median(entered.Select(o => o.PlanPnlPct!.Value))} |");
        md.AppendLine($"| Plan win rate (P&L > 0) | {Rate(entered.Count(o => o.PlanPnlPct > 0), entered.Count)} |");
        md.AppendLine($"| Exits: target / stop / 15:55 | {entered.Count(o => o.ExitReason == "target")} / {entered.Count(o => o.ExitReason == "stop")} / {entered.Count(o => o.ExitReason == "time")} |");
        md.AppendLine($"| Max run after trigger, median | {Median(triggered.Where(o => o.MaxRunAfterTriggerPct != null).Select(o => o.MaxRunAfterTriggerPct!.Value))} |");
        md.AppendLine($"| Max drawdown after trigger, median | {Median(triggered.Where(o => o.MaxDrawdownAfterTriggerPct != null).Select(o => o.MaxDrawdownAfterTriggerPct!.Value))} |");
        md.AppendLine($"| Triggered premarket / gap-through (opened over the trigger) | {triggered.Count(o => o.TriggerUtc is { } u && MinuteBarMath.ToEastern(u).TimeOfDay < MomentumScenarioEvaluator.RthOpen)} / {triggered.Count(o => (o.Notes ?? "").Contains("gap-through"))} |");
        md.AppendLine();
        md.AppendLine("Per pick (best of its scenarios):");
        md.AppendLine();
        md.AppendLine("| metric | value |");
        md.AppendLine("|---|---:|");
        md.AppendLine($"| Picks evaluated | {pickEvaluated.Count} |");
        md.AppendLine($"| Any scenario triggered | {Rate(pickEvaluated.Count(p => p.Os.Any(o => o.TriggerHit)), pickEvaluated.Count)} |");
        md.AppendLine($"| Any scenario hit its first target | {Rate(pickEvaluated.Count(p => p.Os.Any(o => o.FirstTargetHit)), pickEvaluated.Count)} |");
        md.AppendLine($"| Real top gapper that day (gainer rank <= {TopGapperRank} by high over prior close, liquid names) | {Rate(withRank.Count(p => p.Os[0].TopGapper == true), withRank.Count)} |");
        md.AppendLine($"| Gainer rank on the day, median | {MedianInt(withRank.Where(p => p.Os[0].GainerRank != null).Select(p => p.Os[0].GainerRank!.Value))} (unranked = outside the top {MomentumMarketData.KeepTop}: {withRank.Count(p => p.Os[0].GainerRank == null)}) |");
        md.AppendLine($"| Prior session top-{TopGapperRank} gainer by close (what the evening list reacts to) | {Rate(pickOutcomes.Count(p => p.Os[0].PrevDayGainerRank is <= TopGapperRank), pickOutcomes.Count)} |");
        md.AppendLine($"| Day high over prior close, median | {Median(pickOutcomes.Where(p => p.Os[0].DayHighPct != null).Select(p => p.Os[0].DayHighPct!.Value))} |");
        md.AppendLine($"| Close over prior close, median | {Median(pickOutcomes.Where(p => p.Os[0].DayClosePct != null).Select(p => p.Os[0].DayClosePct!.Value))} |");
        md.AppendLine();

        // ── per month ──
        md.AppendLine("## Per month");
        md.AppendLine();
        md.AppendLine("| month | videos | picks | scenarios evaluated | triggered | first target | stopped | mean plan P&L | top gapper |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|");
        foreach (var g in rows.GroupBy(r => r.Claim.TradeDate.ToString("yyyy-MM", CultureInfo.InvariantCulture)).OrderByDescending(g => g.Key))
        {
            var ev = g.Where(r => r.Outcome is { } o && o.Verdict != MomentumVerdicts.Unverifiable).Select(r => r.Outcome!).ToList();
            var tr = ev.Where(o => o.TriggerHit).ToList();
            var pk = g.Select(r => r.Claim).DistinctBy(c => c.Id).ToList();
            var rk = pk.Where(c => byClaim.TryGetValue(c.Id, out var os) && os[0].TopGapper != null).ToList();
            md.AppendLine($"| {g.Key} | {pk.Select(c => c.VideoId).Distinct().Count()} | {pk.Count} | {ev.Count} | {Rate(tr.Count, ev.Count)} | {Rate(tr.Count(o => o.FirstTargetHit), tr.Count)} | {Rate(tr.Count(o => o.Verdict == MomentumVerdicts.Stopped), tr.Count)} | " +
                          $"{Mean(ev.Where(o => o.PlanPnlPct != null).Select(o => o.PlanPnlPct!.Value))} | {Rate(rk.Count(c => byClaim[c.Id][0].TopGapper == true), rk.Count)} |");
        }
        md.AppendLine();

        // ── setups ──
        md.AppendLine("## Setups he uses, and which work");
        md.AppendLine();
        md.AppendLine("Setup tags come from the LLM, one or more per pick; a pick's scenarios all count under each of its tags.");
        md.AppendLine();
        md.AppendLine("| setup tag | picks | scenarios evaluated | trigger rate | first target, of triggered | stopped, of triggered | mean / median plan P&L |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|");
        foreach (var g in rows.SelectMany(r => Tags(r.Claim).DefaultIfEmpty("(none)").Select(t => (Tag: t, Row: r))).GroupBy(x => x.Tag).OrderByDescending(g => g.Select(x => x.Row.Claim.Id).Distinct().Count()))
        {
            var ev = g.Select(x => x.Row.Outcome).Where(o => o is not null && o.Verdict != MomentumVerdicts.Unverifiable).Select(o => o!).ToList();
            var tr = ev.Where(o => o.TriggerHit).ToList();
            var pn = ev.Where(o => o.PlanPnlPct != null).Select(o => o.PlanPnlPct!.Value).ToList();
            md.AppendLine($"| {g.Key} | {g.Select(x => x.Row.Claim.Id).Distinct().Count()} | {ev.Count} | {Rate(tr.Count, ev.Count)} | {Rate(tr.Count(o => o.FirstTargetHit), tr.Count)} | {Rate(tr.Count(o => o.Verdict == MomentumVerdicts.Stopped), tr.Count)} | {Mean(pn)} / {Median(pn)} |");
        }
        md.AppendLine();
        md.AppendLine("| trigger kind | scenarios evaluated | trigger rate | first target, of triggered | of which need a pullback confirm | confirm reached, of triggered needing one | mean plan P&L |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|");
        foreach (var g in rows.Where(r => r.Scenario is not null).GroupBy(r => r.Scenario!.TriggerKind).OrderByDescending(g => g.Count()))
        {
            var ev = g.Select(r => r.Outcome).Where(o => o is not null && o.Verdict != MomentumVerdicts.Unverifiable).Select(o => o!).ToList();
            var tr = ev.Where(o => o.TriggerHit).ToList();
            var needs = g.Count(r => r.Scenario!.RequiresConfirm && r.Outcome is { } oo && oo.Verdict != MomentumVerdicts.Unverifiable);
            md.AppendLine($"| {g.Key} | {ev.Count} | {Rate(tr.Count, ev.Count)} | {Rate(tr.Count(o => o.FirstTargetHit), tr.Count)} | {needs} | {Rate(tr.Count(o => o.ConfirmHit == true), tr.Count(o => o.ConfirmHit != null))} | {Mean(ev.Where(o => o.PlanPnlPct != null).Select(o => o.PlanPnlPct!.Value))} |");
        }
        md.AppendLine();
        var vwapUse = rows.Count(r => r.Scenario is { } sc && (sc.Confirm.Any(l => l.Keyword == "vwap") || sc.Trigger?.Keyword == "vwap"));
        md.AppendLine($"VWAP appears as a trigger or confirm level in {vwapUse} of {rows.Count(r => r.Scenario != null)} scenarios; " +
                      $"{rows.Count(r => r.Scenario?.RequiresConfirm == true)} scenarios want a pullback confirmation before entry.");
        md.AppendLine();

        // ── brags ──
        md.AppendLine("## Past-performance claims (brags)");
        md.AppendLine();
        md.AppendLine($"Accurate when the best actual move (prior close to the window's high, or the window's low to a later high, split-adjusted daily bars) reaches 90% of the claim. " +
                      $"{Rate(bragJudged.Count(b => b.O.Verdict == MomentumVerdicts.BragAccurate), bragJudged.Count)} accurate of {bragJudged.Count} checkable ({brags.Count - bragJudged.Count} not checkable).");
        md.AppendLine();
        if (brags.Count > 0)
        {
            md.AppendLine("| video date | spoken -> ticker | claimed | window | prior close -> high | low -> high | to close | verdict |");
            md.AppendLine("|---|---|---:|---|---:|---:|---:|---|");
            foreach (var b in brags.OrderByDescending(b => b.TradeDate))
            {
                var o = byClaim.GetValueOrDefault(b.Id)?.FirstOrDefault();
                md.AppendLine($"| {b.TradeDate:yyyy-MM-dd} | {Esc(b.SpokenSymbol)} -> {b.Symbol ?? "?"} | {(b.ClaimedPct is { } cp ? $"+{cp:0}%" : "—")} | {b.ClaimWindow ?? "—"} | {P(o?.BragActualHighPct)} | {P(o?.BragActualLowToHighPct)} | {P(o?.BragActualClosePct)} | {o?.Verdict ?? "pending"} |");
            }
            md.AppendLine();
        }

        if (statements.Count > 0)
        {
            md.AppendLine("## Market statements (recorded, not scored)");
            md.AppendLine();
            foreach (var m in statements.OrderByDescending(m => m.TradeDate).Take(40)) md.AppendLine($"- {m.TradeDate:yyyy-MM-dd}: {Esc(m.IdentityHint)}");
            md.AppendLine();
        }

        // ── per video ──
        md.AppendLine("## Every pick, newest first");
        md.AppendLine();
        md.AppendLine("Times ET. Plan = trigger kind and level, confirm levels (C), targets (T). Rank = gainer rank by high on the day / by close on the prior session (— = outside the top 300 or not computed).");
        md.AppendLine();
        md.AppendLine("| date | video | # | spoken -> ticker | tags | plan | triggered | entry | first target | exit | plan P&L | run / DD | verdict | rank D / D-1 |");
        md.AppendLine("|---|---|---:|---|---|---|---|---:|---|---|---:|---|---|---|");
        foreach (var r in rows.OrderByDescending(r => r.Claim.TradeDate).ThenByDescending(r => r.Video?.PublishedUtc).ThenBy(r => r.Claim.Rank).ThenBy(r => r.Outcome?.ScenarioIndex))
        {
            var c = r.Claim; var o = r.Outcome; var sc = r.Scenario;
            var vid = r.Video is { } v ? $"[{(v.Kind == "morning-update" ? "update" : v.Kind)}]({v.Url})" : c.VideoId;
            var plan = sc is null ? "—" : $"{sc.TriggerKind} {Lv(sc.Trigger)}" + (sc.Confirm.Count > 0 ? $"; C {string.Join(",", sc.Confirm.Select(Lv))}{(sc.RequiresConfirm ? "*" : "")}" : "") +
                                          (sc.Targets.Count > 0 ? $"; T {string.Join(",", sc.Targets.Select(Lv))}" : "");
            md.AppendLine($"| {c.TradeDate:yyyy-MM-dd} | {vid} | {c.Rank} | {Esc(c.SpokenSymbol ?? "(" + Trim(c.IdentityHint, 30) + ")")} -> {c.Symbol ?? "?"}{(c.SymbolConfidence is { } cf && cf < 0.6 ? $" ({cf:0.00})" : "")} | {string.Join(", ", Tags(c))} | {Esc(plan)} | " +
                          $"{(o is null ? (IsComplete(c.TradeDate) ? "not verified" : "pending") : o.TriggerHit ? T(o.TriggerUtc) : "no")} | {Px(o?.EntryPrice)} | {(o?.FirstTargetHit == true ? T(o.FirstTargetUtc) : o is null ? "" : "no")} | " +
                          $"{(o?.ExitReason is { } er ? $"{er} {Px(o.ExitPrice)}" : "")} | {P(o?.PlanPnlPct)} | {(o?.MaxRunAfterTriggerPct is { } mr ? $"{P(mr)} / {P(o.MaxDrawdownAfterTriggerPct)}" : "")} | {o?.Verdict ?? ""} | " +
                          $"{(o?.GainerRank?.ToString(CultureInfo.InvariantCulture) ?? "—")} / {(o?.PrevDayGainerRank?.ToString(CultureInfo.InvariantCulture) ?? "—")} |");
        }
        md.AppendLine();
        md.AppendLine("\\* the plan enters only on a pullback that holds a confirm level.");
        md.AppendLine();

        // ── method ──
        md.AppendLine("## Method");
        md.AppendLine();
        md.AppendLine("- **Collection:** `tools/momentum/fetch_momentum.py` keeps shorts whose title starts with TOP/Top or carries a date and saves YouTube captions per trade day; `momentum import` upserts them (idempotent).");
        md.AppendLine("- **Extraction:** the transcript goes to the LLM in the user message only (untrusted text), with a strict JSON schema; levels are copied as spoken. The spoken-price resolver scales a bare number by 1, 1/10 or 1/100 to the one closest to the stock's split-consistent prior close (and the day's open): \"270\" = $2.70, \"56\" = $5.60; \"$3.50\", \"five bucks\" are literal.");
        md.AppendLine("- **Tickers:** each spoken ticker (spelled letters joined: \"P A R A\" = PARA) is validated against active Alpaca assets and the prior/same session's top movers, with one-letter fixes for misheard captions; a pick named only by description (\"the one that closed up over 80%\") is identified from the prior session's top gainers by the stated move and the level scale, at lower confidence.");
        md.AppendLine("- **Trigger:** break = a 1-minute high over the level (entry at the level, or the open when the bar opened over it); reclaim = trades under the level, then a close back over it; hold = pulls to within 3% of the level, then closes over that pullback bar's high. Triggers count from 04:00 to 15:55 ET.");
        md.AppendLine("- **Confirm and entry:** when he wants a pullback confirmation, the plan enters at the close of the first bar after the trigger that dips to within 2% of a confirm level (or VWAP from 04:00) and closes at or over it; otherwise at the trigger price. No confirm, no entry.");
        md.AppendLine("- **Targets and stop:** a target is hit when a bar's high reaches it. The invalidation is the level he states, else the lowest confirm level, else VWAP, else the trigger level, hit by a 1-minute close under it. Plan P&L exits at the first target, the stop, or the 15:55 bar's close; no costs or slippage.");
        md.AppendLine($"- **Top gapper:** rank by the day's high over the split-consistent prior close among every active Alpaca stock with prior close >= $0.10 and >= $1M traded; top {TopGapperRank} counts as a real top gapper.");
        md.AppendLine("- **Brags:** daily split-adjusted bars over the stated window (previous session, last week, this week, or the last two weeks).");
        md.AppendLine();
        md.AppendLine("## Caveats");
        md.AppendLine();
        md.AppendLine("- Captions mishear tickers and prices; low-confidence tickers are marked and morning updates can name a different stock than the evening list.");
        md.AppendLine("- He gives levels from a chart we do not see; a level we cannot price (\"the recent high\") makes that scenario unverifiable rather than guessed.");
        md.AppendLine("- Entries on a gap-through or premarket trigger use prices a retail order might not get; the plan P&L is an upper bound of what following the words literally would return.");
        if (lockedHoldout > 0)
            md.AppendLine($"- {lockedHoldout} claim(s) fall inside the gapper study's locked holdout ({StudyLockedHoldout.From:yyyy-MM-dd}..{StudyLockedHoldout.To:yyyy-MM-dd}). Their outcomes describe Momentum.'s calls only; do not use them to choose or tune gapper-study hypotheses.");
        md.AppendLine();

        var path = string.IsNullOrWhiteSpace(outPath) ? DefaultReportPath() : outPath;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await File.WriteAllTextAsync(path, md.ToString(), ct);

        var human = new StringBuilder();
        human.AppendLine($"Momentum. claim tracker report -> {path}");
        human.AppendLine($"  videos {videos.Count}, transcripts {transcripts.Count} ({transcripts.Count(t => t.HasText)} with text), extracted {transcripts.Count(t => t.ExtractedUtc != null)}; picks {picks.Count}, brags {brags.Count}, statements {statements.Count}; pending {pending}");
        human.AppendLine($"  scenarios evaluated {evaluated.Count}: trigger {Rate(triggered.Count, evaluated.Count)}, first target {Rate(triggered.Count(o => o.FirstTargetHit), triggered.Count)} of triggered, any target {Rate(triggered.Count(o => o.AnyTargetHit), triggered.Count)}, stopped {Rate(triggered.Count(o => o.Verdict == MomentumVerdicts.Stopped), triggered.Count)}");
        human.AppendLine($"  plan P&L ({entered.Count} entered): mean {Mean(entered.Select(o => o.PlanPnlPct!.Value))}, median {Median(entered.Select(o => o.PlanPnlPct!.Value))}; top gapper {Rate(withRank.Count(p => p.Os[0].TopGapper == true), withRank.Count)} of picks");
        human.AppendLine($"  brags accurate {Rate(bragJudged.Count(b => b.O.Verdict == MomentumVerdicts.BragAccurate), bragJudged.Count)} of {bragJudged.Count}");
        human.AppendLine("  top setups: " + string.Join(", ", picks.SelectMany(Tags).GroupBy(t => t).OrderByDescending(g => g.Count()).Take(6).Select(g => $"{g.Key} {g.Count()}")));
        foreach (var r in rows.Where(r => r.Outcome is not null).OrderByDescending(r => r.Claim.TradeDate).ThenBy(r => r.Claim.Rank).Take(15))
            human.AppendLine($"  {r.Claim.TradeDate:yyyy-MM-dd} #{r.Claim.Rank} {r.Claim.Symbol ?? "?",-6} {r.Scenario?.TriggerKind} {Lv(r.Scenario?.Trigger)} -> {r.Outcome!.Verdict}" +
                             (r.Outcome.TriggerHit ? $" at {T(r.Outcome.TriggerUtc)}" : "") + (r.Outcome.PlanPnlPct is { } pp ? $", plan {P(pp)}" : ""));
        return new(true, human.ToString().TrimEnd(), new
        {
            path, videos = videos.Count, transcripts = transcripts.Count, picks = picks.Count, brags = brags.Count, statements = statements.Count,
            evaluated = evaluated.Count, triggered = triggered.Count, firstTarget = triggered.Count(o => o.FirstTargetHit), anyTarget = triggered.Count(o => o.AnyTargetHit),
            stopped = triggered.Count(o => o.Verdict == MomentumVerdicts.Stopped), entered = entered.Count,
            meanPlanPnl = entered.Count > 0 ? entered.Average(o => o.PlanPnlPct!.Value) : (double?)null,
            topGapper = withRank.Count(p => p.Os[0].TopGapper == true), ranked = withRank.Count,
            bragsAccurate = bragJudged.Count(b => b.O.Verdict == MomentumVerdicts.BragAccurate), bragsJudged = bragJudged.Count, pending,
        });
    }

    private static string Rate(int n, int d) => d == 0 ? "—" : $"{100.0 * n / d:0}% ({n}/{d})";
    private static string P(double? v) => v is { } x ? x.ToString("+0.0;-0.0;0.0", CultureInfo.InvariantCulture) + "%" : "—";
    private static string Mean(IEnumerable<double> xs) { var l = xs.ToList(); return l.Count == 0 ? "—" : P(l.Average()); }
    private static string Median(IEnumerable<double> xs)
    {
        var l = xs.OrderBy(x => x).ToList();
        if (l.Count == 0) return "—";
        return P(l.Count % 2 == 1 ? l[l.Count / 2] : (l[l.Count / 2 - 1] + l[l.Count / 2]) / 2);
    }
    private static string MedianInt(IEnumerable<int> xs)
    {
        var l = xs.OrderBy(x => x).ToList();
        return l.Count == 0 ? "—" : l[l.Count / 2].ToString(CultureInfo.InvariantCulture);
    }
    private static string Px(decimal? v) => v is { } x ? "$" + x.ToString(x < 1 ? "0.0000" : "0.00", CultureInfo.InvariantCulture) : "";
    private static string T(DateTime? utc) => utc is { } u ? MinuteBarMath.ToEastern(u).ToString("HH:mm", CultureInfo.InvariantCulture) : "";
    private static string Lv(StoredLevel? l) => l is null ? "?" : l.Keyword == "vwap" ? "VWAP" : l.Price is { } p ? Px(p) : l.Keyword ?? $"'{l.Spoken}'";
    private static string Esc(string? s) => (s ?? "").Replace("|", "/").Replace("\n", " ");
    private static string Trim(string? s, int n) => s is null ? "?" : s.Length <= n ? s : s[..n] + "…";
