using System.Text;
using System.Text.Json;

namespace IdiotProof.Mcp;

/// <summary>Renders docs/MCP_TOOLS.md from the generated tool list (never hand-edited).</summary>
public static class ToolDocs
{
    public static string Render(IReadOnlyList<ToolSpec> tools)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# IdiotProof MCP tools");
        sb.AppendLine();
        sb.AppendLine("<!-- Generated by `dotnet run --project IdiotProof.Mcp -- --export-tools`. Do not hand-edit. -->");
        sb.AppendLine();
        sb.AppendLine($"{tools.Count} tools, one per Hub operation. Each forwards to the running Hub; `money` tools return a");
        sb.AppendLine("confirmation code for Live actions instead of executing them. Times are US Eastern.");
        sb.AppendLine();
        sb.AppendLine("| Tool | Operation | Risk |");
        sb.AppendLine("|---|---|---|");
        foreach (var t in tools) sb.AppendLine($"| `{t.ToolName}` | `{t.Operation}` | {t.Risk} |");

        foreach (var t in tools)
        {
            sb.AppendLine();
            sb.AppendLine($"## `{t.ToolName}`");
            sb.AppendLine();
            sb.AppendLine(t.Description);
            sb.AppendLine();
            sb.AppendLine("```json");
            sb.AppendLine(JsonSerializer.Serialize(t.InputSchema, new JsonSerializerOptions { WriteIndented = true }));
            sb.AppendLine("```");
        }
        return sb.ToString().ReplaceLineEndings("\n");
    }
}
